const STRINGS = { en, hi, bn, mr, te, ta, gu, or }

const fill = (str, vars) => {
  if (!str) return ''
  return String(str).replace(/\{(\w+)\}/g, (_, k) => (vars && vars[k] !== undefined ? vars[k] : `{${k}}`))
}

export function t(lang, key, vars) {
  const pack = STRINGS[lang] || {}
  const raw = pack[key] !== undefined ? pack[key] : en[key]
  if (raw === undefined) return key
  return fill(raw, vars)
}

/** Plural helper: tCount(lang, 'papersCount', 2) -> "2 papers to carry" */
export function tCount(lang, key, n) {
  const pack = STRINGS[lang] || {}
  const entry = pack[key] !== undefined ? pack[key] : en[key]
  if (!entry) return `${n}`
  const form = n === 1 ? entry.one : entry.other
  return fill(form || entry.other || '', { n })
}

